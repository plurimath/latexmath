# frozen_string_literal: true

# Writes lib/latexmath/model/nodes.rb, the plain LML classes of the LaTeX
# model, from the static capture shapes of the normalized grammar
# (grammars/latex.normalized-rules.json, written by
# scripts/generate_grammar.rb).
#
# Usage:
#   ruby scripts/generate_model.rb            write the classes
#   ruby scripts/generate_model.rb --check    exit 1 if they are stale
#
# After normalization every capture holds one kind, so the mapping is
# mechanical and needs no union, cast hook or walker:
#
#   capture of kind hash  -> class <Capture>, one attribute per key
#   capture of kind list  -> class <Capture>Item for the elements; the
#                            attribute is a collection of it
#   capture of kind text  -> :string attribute
#   catalog capture       -> MathSymbol (a hash whose only key is spelling)
#
# An attribute has the same name and type wherever it occurs, because its
# type is the type of the capture it names. Capture names the grammar
# spells differently (renames) are used as the grammar spells them.

require "json"
require_relative "normalize_shapes"

ROOT = File.expand_path("..", __dir__)
RULES = File.join(ROOT, "grammars/latex.normalized-rules.json")
OUT = File.join(ROOT, "lib/latexmath/model/nodes.rb")
TREE = "latex_tree"
NS = "Latexmath::Model"
RESERVED = { "array" => "ArrayNode", "symbol" => "SymbolNode", "root" => "RootNode" }.freeze
SPELLING = "spelling"
SYMBOL_CLASS = "MathSymbol"

check = ARGV.delete("--check")
abort "usage: ruby scripts/generate_model.rb [--check]" unless ARGV.empty?

doc = JSON.parse(File.read(RULES, encoding: "UTF-8"))
renames = doc.fetch("renames")
shapes = ShapeNormalizer.new(doc.fetch("rules"), normalized: true)
caps = shapes.solve
# The generator wraps the root rule in the tree capture; add its shape.
caps[TREE] = shapes.shape({ "ref" => doc.fetch("root") }, true)

kind = lambda do |name|
  shape = caps.fetch(name)
  solid = shape.solid
  abort "capture #{name} holds #{shape.kinds.to_a.join('|')}; normalize the grammar first" unless solid.size <= 1 && !shape.kinds.include?(:nil)
  solid.first || :string
end
spelled = ->(n) { renames.fetch(n, n) }
camel = ->(n) { RESERVED[n] || spelled.call(n).split("_").map { |w| w[0].upcase + w[1..] }.join }
symbol = ->(name) { kind.call(name) == :hash && caps[name].hash_keys.to_a == [SPELLING] }
abort "#{SPELLING} must hold text" unless caps.key?(SPELLING) && kind.call(SPELLING) == :string

classes = {} # class name => [capture, attribute keys]
caps.keys.sort.each do |name|
  next if symbol.call(name)

  case kind.call(name)
  when :hash then classes[camel.call(name)] = [name, caps[name].hash_keys.to_a.sort_by { |k| spelled.call(k) }]
  when :array then classes["#{camel.call(name)}Item"] = [name, caps[name].array_keys.to_a.sort_by { |k| spelled.call(k) }]
  end
end
abort "a capture is named like #{SYMBOL_CLASS}" if classes.key?(SYMBOL_CLASS)

type_of = lambda do |key|
  if symbol.call(key) then %("#{NS}::#{SYMBOL_CLASS}")
  else
    case kind.call(key)
    when :hash then %("#{NS}::#{camel.call(key)}")
    when :array then %("#{NS}::#{camel.call(key)}Item", collection: true)
    else ":string"
    end
  end
end

out = +<<~RUBY
  # frozen_string_literal: true

  # GENERATED by scripts/generate_model.rb from the normalized grammar's
  # capture shapes -- do not edit. #{classes.size + 2} classes.
  module Latexmath
    module Model
RUBY
classes.sort.each do |cname, (capture, keys)|
  what = cname.end_with?("Item") && kind.call(capture) == :array ? "An element of capture" : "Capture"
  out << "    # #{what} +#{spelled.call(capture)}+.\n    class #{cname} < Lutaml::Model::Serializable\n"
  keys.each { |k| out << "      attribute :#{spelled.call(k)}, #{type_of.call(k)}\n" }
  out << "    end\n\n"
end
out << <<~RUBY
    # A catalog capture (+symbols+, +unicode_symbols+): the spelling the
    # grammar matched. Its Unicode value and kind are read from the symbol
    # table (lib/latexmath/model.rb).
    class #{SYMBOL_CLASS} < Lutaml::Model::Serializable
      attribute :spelling, :string
    end

    # The root: one parsed formula (binding +model+), and the decimal
    # marker it was parsed with.
    class Document < Lutaml::Model::Serializable
      attribute :expression, "#{NS}::#{camel.call(TREE)}"
      attribute :decimal, :string
    end
  end
end
RUBY

if check
  exit(File.exist?(OUT) && File.read(OUT, encoding: "UTF-8") == out ? 0 : 1)
else
  File.write(OUT, out)
  puts "wrote #{OUT.delete_prefix("#{ROOT}/")}: #{classes.size + 2} classes"
end
